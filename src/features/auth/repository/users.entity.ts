/**
 * Persisted shape of a row in the `users` table (see `init.sql`).
 *
 * Column names mirror the database (snake_case); mapping to the public API
 * shape happens in the feature's `response/` DTOs.
 *
 * Two identifiers exist on purpose:
 * - `id`        — internal `BIGSERIAL` surrogate key, used for joins/FKs only.
 * - `public_id` — UUID exposed to clients. **Never serialize `id`.**
 */
export interface UserEntity {
  /** Internal surrogate key (`BIGSERIAL`, returned by `pg` as a string). */
  id: string;

  /** Public UUID exposed by the API. */
  public_id: string;

  username: string;
  email: string;
  password_hash: string;
  display_name: string | null;
  avatar_url: string | null;
  /** Future E2EE: public key material (nullable for now). */
  public_key: string | null;
  key_version: number;
  is_active: boolean;
  last_seen_at: Date | null;
  created_at: Date;
  updated_at: Date;
}

/**
 * Fields accepted when creating a user. `id` and `public_id` are generated by
 * the database, so they are intentionally excluded.
 */
export type NewUserEntity = Pick<
  UserEntity,
  'username' | 'email' | 'password_hash'
> &
  Partial<
    Pick<
      UserEntity,
      'display_name' | 'avatar_url' | 'public_key' | 'key_version'
    >
  >;
